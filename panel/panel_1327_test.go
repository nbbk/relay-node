// ---------- 问题二之四：本地全 0 空壳不能遮住聚合缓存 ----------
// 管理面板上 enforceUserTrafficLimits 每分钟会对每条限流转发调
// get()，远程专属转发也在本机建出一条全 0 的空壳记录；旧的读路
// 径本地优先，把空壳当真 0 返回，聚合缓存（本地+远程之和）永远
// 查不到，远程用量再多列表与头也显示 0。修后缓存优先、本地回落。

func TestCentralCachePreferredOverLocalStub1327(t *testing.T) {
	s := newTestManagerServer1327(t)
	key := indMergedSubKey("ims-1327")
	const mb = int64(1024 * 1024)
	// 本地空壳记录（全 0）：enforceUserTrafficLimits 建的那种。
	_ = s.userTraffic.get(key)
	// 聚合缓存：远程已上报 3MB 上行 + 2MB 下行（本期同值）。
	s.centralUserUsageMu.Lock()
	s.centralUserUsage[key] = &centralUserUsage{UpTotal: 3 * mb, DownTotal: 2 * mb, UpPeriod: 3 * mb, DownPeriod: 2 * mb, UpdatedAt: time.Now()}
	s.centralUserUsageMu.Unlock()
	// 列表摘要：应用缓存的 5MB，不是本地的 0。
	used, limit, ok := s.userUsageSummary(key, 1024*mb, "total")
	if !ok || used != 5*mb || limit != 1024*mb {
		t.Fatalf("列表用量应用聚合缓存 5MB，实际 used=%d limit=%d ok=%v（本地空壳遮住了缓存）", used, limit, ok)
	}
	// 订阅头：upload/download 也应是缓存的 3MB/2MB。
	h := s.subUserinfoHeaderForUser(key, 1024*mb, "total", "", nil)
	want := "upload=" + strconv.FormatInt(3*mb, 10) + "; download=" + strconv.FormatInt(2*mb, 10) + "; total=" + strconv.FormatInt(1024*mb, 10) + "; expire=0"
	if h != want {
		t.Fatalf("userinfo 头应用聚合缓存，期望 %q，实际 %q", want, h)
	}
	// 回落：缓存没有时仍用本地记录（本机落地订阅不受影响）。
	key2 := indMergedSubKey("ims-local")
	s.userTraffic.addDelta(key2, map[string][2]int64{"tcp:30001": {mb, 2 * mb}})
	used2, _, ok2 := s.userUsageSummary(key2, 1024*mb, "total")
	if !ok2 || used2 != 3*mb {
		t.Fatalf("无缓存时列表应用本地记录 3MB，实际 used=%d ok=%v", used2, ok2)
	}
}
