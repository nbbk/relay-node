func TestSamplingSurvivesEnforceFlush1327(t *testing.T) {
	s, state := newTestSamplingServer1327(t)
	key := indMergedSubKey("ims-1327")

	// 先建链（模拟“落地早就加上了，链已建好”）：tick1 时计数还是 0，
	// 首采按 0 起算计入 0；之后两分钟的流量都要被计上（建链后、首采
	// 前来的流量也会被计入，见 TestFirstSampleCountsTraffic1327）。
	rc, _, err := s.readRelayConf()
	if err != nil {
		t.Fatal(err)
	}
	if err := s.ensureTrafficChains(rc.Landings); err != nil {
		t.Fatalf("建链失败：%v", err)
	}

	// trafficLoop 的一节拍（顺序与 background.go 一致：先采后执法）。
	tick := func() {
		s.sampleTraffic()
		s.sampleUserTraffic()
		s.enforceTrafficLimits()
		s.enforceUserTrafficLimits()
	}
	const mb = int64(1024 * 1024)
	// 第 1 分钟：建链、定基线（不计）。
	tick()
	// 第 2 分钟：用户端口与落地端口各流 1MB 上行 + 1MB 下行。
	fakeIptBump(t, state, "RELAY-PANEL-IN", "dport", 30000, mb)
	fakeIptBump(t, state, "RELAY-PANEL-OUT", "sport", 30000, mb)
	fakeIptBump(t, state, "RELAY-PANEL-IN", "dport", 24443, mb)
	fakeIptBump(t, state, "RELAY-PANEL-OUT", "sport", 24443, mb)
	tick()
	// 第 3 分钟：再流同样 1MB + 1MB（稳态流量，验证不只计第一分钟）。
	fakeIptBump(t, state, "RELAY-PANEL-IN", "dport", 30000, mb)
	fakeIptBump(t, state, "RELAY-PANEL-OUT", "sport", 30000, mb)
	fakeIptBump(t, state, "RELAY-PANEL-IN", "dport", 24443, mb)
	fakeIptBump(t, state, "RELAY-PANEL-OUT", "sport", 24443, mb)
	tick()

	up, down, _, _, ok := s.userTraffic.totals(key)
	if !ok {
		t.Fatalf("按人流量应有记录")
	}
	if up < mb+mb/2 || down < mb+mb/2 {
		t.Fatalf("两分钟各流 2MB 上行+2MB 下行，按人应累计约 2MB+2MB，实际 up=%d down=%d（清链后采样丢数）", up, down)
	}
	lt := s.traffic.get("203.0.113.1")
	if lt == nil {
		t.Fatalf("落地流量应有记录")
	}
	if lt.UpTotal < mb+mb/2 || lt.DownTotal < mb+mb/2 {
		t.Fatalf("两分钟各流 2MB 上行+2MB 下行，落地应累计约 2MB+2MB，实际 up=%d down=%d（基线未清零丢了第二分钟）", lt.UpTotal, lt.DownTotal)
	}
	_ = time.Now
}

