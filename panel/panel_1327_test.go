// ---------- v1.3.27：三处真机问题 ----------
// 问题一：管理面板模式下小火箭到期时间仍显示导入时间——
//   subUserinfoHeader 开头读 relay.conf 失败就直接 return ""，管理面板
//   本机没有 relay.conf，所有订阅都不带 subscription-userinfo 头。
// 问题二：按人流量统计基本没用——三条根因（e2e 真实流量定位）：
//   ①采样顺序：trafficLoop 里 sampleTraffic 后 enforceTrafficLimits
//     末尾调 ensureTrafficChains 把链 -F 清掉，按人采样 sampleUserTraffic
//     跑在清链之后，读到的永远是刚重建的 ≈0；落地采样虽在清链前读，
//     但不清基线时 deltaCounter 的 cur<prev→0 让落地也只计第一分钟。
//   ②首见丢数：addDelta 首见只定基线不计，转发建好、用户立即使用，
//     第一个 60 秒内的流量在首采时被当成基线丢掉（e2e 里 5MB 真实
//     流量就这样丢了）。截图的 1.69 KB 就是建链后、首采前毫秒窗口
//     里的一次握手/探针被当成基线后、下一分钟又被清链丢掉的残数。
//   ③本地空壳遮住聚合缓存：管理面板上 enforceUserTrafficLimits
//     每分钟对每条限流转发调 get()，远程专属转发也在本机建出一条
//     全 0 的空壳记录；userUsageSummary 与 subUserinfoHeaderForUser
//     本地优先，把空壳当真 0 返回，聚合缓存（本地+远程之和）永远
//     查不到，远程用量再多列表与头也显示 0。
// 问题三：合并订阅编辑弹窗到期时间行错位、弹窗超高按钮被切（见 jsdom）。

// ---------- 假 iptables：按 PATH 上的 iptables/iptables-save 建模 ----------
// 状态文件（FAKE_IPT_STATE 环境变量指向）：
//   RULE|链|协议|dport|端口|quota|包数|字节数
//   JUMP|INPUT|链
//   CHAIN|链
// 语义与真 iptables 一致的关键点：-F 清掉规则时计数器跟着丢（重建后从 0
// 开始）；bump 只给已装上的规则加数（没装规则的流量不会被计上）。

const fakeIptablesPy = `#!/usr/bin/env python3
import os, sys
state = os.environ["FAKE_IPT_STATE"]
def load():
    try:
        with open(state) as f:
            return [l.rstrip("\n") for l in f if l.strip()]
    except FileNotFoundError:
        return []
def save(lines):
    with open(state, "w") as f:
        for l in lines:
            f.write(l + "\n")
args = sys.argv[1:]
lines = load()
def has_jump(chain):
    return any(l == "JUMP|INPUT|" + chain for l in lines)
if args[:1] == ["-N"]:
    name = args[1]
    if not any(l == "CHAIN|" + name for l in lines):
        lines.append("CHAIN|" + name)
    save(lines)
    sys.exit(0)
if args[:1] == ["-C"]:
    chain = args[args.index("-j") + 1]
    sys.exit(0 if has_jump(chain) else 1)
if args[:1] == ["-I"]:
    chain = args[args.index("-j") + 1]
    if not has_jump(chain):
        lines.append("JUMP|INPUT|" + chain)
    save(lines)
    sys.exit(0)
if args[:1] == ["-F"]:
    chain = args[1]
    lines = [l for l in lines if not l.startswith("RULE|" + chain + "|")]
    save(lines)
    sys.exit(0)
if args[:1] == ["-A"]:
    chain = args[1]
    proto = args[args.index("-p") + 1]
    match = "dport" if "--dport" in args else ("sport" if "--sport" in args else "")
    port = args[args.index("--" + match) + 1] if match else "0"
    quota = "0"
    if "quota" in args:
        quota = args[args.index("--quota") + 1]
    lines.append("RULE|%s|%s|%s|%s|%s|0|0" % (chain, proto, match, port, quota))
    save(lines)
    sys.exit(0)
if args[:1] == ["-L"]:
    sys.exit(0)
sys.exit(0)
`

const fakeIptablesSavePy = `#!/usr/bin/env python3
import os, sys
state = os.environ["FAKE_IPT_STATE"]
lines = []
try:
    with open(state) as f:
        lines = [l.rstrip("\n") for l in f if l.strip()]
except FileNotFoundError:
    pass
print("# Generated by iptables-save v1.8.7 (fake)")
print("*filter")
for l in lines:
    p = l.split("|")
    if p[0] != "RULE":
        continue
    _, chain, proto, match, port, quota, pkts, byts = p
    q = (" -m quota --quota %s" % quota) if quota != "0" else ""
    print("[%s:%s] -A %s -p %s -m %s --%s %s%s -j RETURN" % (pkts, byts, chain, proto, proto, match, port, q))
print("COMMIT")
`

// setupFakeIptables 在 PATH 最前面放假 iptables/iptables-save，返回状态文件路径。
func setupFakeIptables(t *testing.T) string {
	t.Helper()
	dir := t.TempDir()
	state := filepath.Join(dir, "state.txt")
	for name, src := range map[string]string{"iptables": fakeIptablesPy, "iptables-save": fakeIptablesSavePy} {
		if err := os.WriteFile(filepath.Join(dir, name), []byte(src), 0o755); err != nil {
			t.Fatal(err)
		}
	}
	t.Setenv("FAKE_IPT_STATE", state)
	t.Setenv("PATH", dir+string(os.PathListSeparator)+os.Getenv("PATH"))
	return state
}

// fakeIptBump 模拟内核计数：给已装上的规则加字节数（上行/下行分开调）。
// 规则不存在时什么都不做——像真机上没装规则的流量不会被计上。
// 同一端口有多条规则时只加第一条：真实包命中 quota RETURN 就返回，
// 不会再走到后面的 DROP 规则（parseIptablesSave 求和时 DROP 那条是 0）。
func fakeIptBump(t *testing.T, state, chain, match string, port int, nbytes int64) {
	t.Helper()
	b, err := os.ReadFile(state)
	if err != nil {
		t.Fatal(err)
	}
	var out []string
	hit := false
	for _, ln := range strings.Split(strings.TrimRight(string(b), "\n"), "\n") {
		if ln == "" {
			continue
		}
		p := strings.Split(ln, "|")
		if !hit && len(p) == 8 && p[0] == "RULE" && p[1] == chain && p[3] == match && p[4] == strconv.Itoa(port) {
			pkts, _ := strconv.ParseInt(p[6], 10, 64)
			byts, _ := strconv.ParseInt(p[7], 10, 64)
			p[6] = strconv.FormatInt(pkts+1, 10)
			p[7] = strconv.FormatInt(byts+nbytes, 10)
			ln = strings.Join(p, "|")
			hit = true
		}
		out = append(out, ln)
	}
	if !hit {
		t.Fatalf("假 iptables 里找不到规则 %s %s %d（规则没装上）", chain, match, port)
	}
	if err := os.WriteFile(state, []byte(strings.Join(out, "\n")+"\n"), 0o644); err != nil {
		t.Fatal(err)
	}
}

